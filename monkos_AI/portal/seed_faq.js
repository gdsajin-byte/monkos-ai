async function seed() {
  // 1. 기존 데이터 확인 및 백업 (헌법 4조 1항)
  console.log('=== faq_items 기존 데이터 확인 ===');
  const existing = await collection.get();
  if (existing.size > 0) {
    console.log(`기존 ${existing.size}건 발견 — 백업 출력 후 삭제`);
    for (const doc of existing.docs) {
      console.log(`  [백업] ${doc.id}: ${doc.data().question || '(no question)'}`);
    }
    // 기존 데이터 삭제
    const batch = firestore.batch();
    for (const doc of existing.docs) {
      batch.delete(doc.ref);
    }
    await batch.commit();
    console.log(`기존 ${existing.size}건 삭제 완료`);
  } else {
    console.log('기존 데이터 없음 — 클린 시딩 진행');
  }

  // 2. FAQ 시딩
  console.log('\n=== FAQ 시딩 시작 (Q1~Q13 한국어) ===');
  const now = new Date().toISOString();
  for (const item of faqItems) {
    const { id, ...data } = item;
    data.lang = 'ko';
    data.published = true;
    data.createdAt = now;
    data.updatedAt = now;
    await collection.doc(id).set(data);
    console.log(`  ✓ ${id}: ${data.question}`);
  }
  console.log(`\n완료: ${faqItems.length}건 시딩됨`);
}

seed().catch(console.error);
